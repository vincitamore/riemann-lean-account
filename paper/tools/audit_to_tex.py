"""Turn the audit table (Markdown) into the LaTeX appendix.

Usage: python tools/audit_to_tex.py ../notes/audit-of-the-one-page-draft.md sections/appendix-audit.tex
"""
import re
import sys

from leanfmt import leanb

LEVEL = {"S": r"\textsf{S}", "P": r"\textsf{P}", "D": r"\textsf{R}", "M": r"\textsf{M}", "C": r"\textsf{C}"}

SUBS = [
    ("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_"),
    ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}"),
]
UNI = {
    "≤": r"$\le$", "≥": r"$\ge$", "−": "--", "·": r"$\cdot$", "Σ": r"$\Sigma$", "μ": r"$\mu$",
    "γ": r"$\gamma$", "π": r"$\pi$", "τ": r"$\tau$", "η": r"$\eta$", "χ": r"$\chi$", "ℓ": r"$\ell$",
    "ε": r"$\varepsilon$", "λ": r"$\lambda$", "Ω": r"$\Omega$", "ψ": r"$\psi$", "√": r"$\surd$",
    "′": "'", "→": r"$\to$", "…": r"\ldots{}", "²": r"\textsuperscript{2}", "⁴": r"\textsuperscript{4}",
    "₂": r"\textsubscript{2}", "𝔓": r"$\mathfrak{P}$", "⌊": r"$\lfloor$", "⌋": r"$\rfloor$", "∈": r"$\in$",
    "≈": r"$\approx$", "×": r"$\times$", "–": "--", "—": "---", "’": "'", "“": "``", "”": "''",
    "ö": r"\"o", "é": r"\'e", "ℚ": r"$\mathbb{Q}$", "ℤ": r"$\mathbb{Z}$", "ℂ": r"$\mathbb{C}$",
    "|": r"$\vert$",
}


def esc(text: str) -> str:
    for a, b in SUBS:
        text = text.replace(a, b)
    for a, b in UNI.items():
        text = text.replace(a, b)
    return text


def cell(text: str) -> str:
    """Escape prose; set `code` spans in typewriter with breakable paths."""
    out = []
    for i, part in enumerate(re.split(r"`([^`]*)`", text)):
        if i % 2 == 1:
            out.append(leanb(part))
        else:
            part = re.sub(r"\*\*(.+?)\*\*", r"@@B@@\1@@E@@", part)
            part = esc(part)
            out.append(part.replace("@@B@@", r"\textbf{").replace("@@E@@", "}"))
    return "".join(out)


def level(text: str) -> str:
    text = text.strip()
    head = text[:1]
    if head in LEVEL and (len(text) == 1 or not text[1].isalpha()):
        rest = text[1:].strip()
        return LEVEL[head] + ((" " + cell(rest)) if rest else "")
    return cell(text)


def main(src: str, dst: str) -> None:
    rows = []
    for line in open(src, encoding="utf-8"):
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split(" | ")]
        if len(cells) != 4 or cells[0].startswith("---") or cells[0] in ("Draft step", "Section"):
            continue
        rows.append(cells)
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("% Generated by tools/audit_to_tex.py from the audit note. Do not edit by hand.\n")
        f.write("\\section{Basis of the statements}\\label{app:audit}\n\n")
        f.write(
            "This appendix records the basis of the paper's statements about the proof. "
            "\\textsf{M}: computed from the compiled files, of the archive or, where the row says "
            "so, of Mathlib. \\textsf{S}: the Lean statement was "
            "read and transcribed by the authors. \\textsf{P}: the Lean source was read by the "
            "authors. \\textsf{C}: the Lean statement was compared by the authors with the "
            "published theorem as they know it, without opening the papers. \\textsf{R}: taken "
            "from a reader's report, published with this "
            "paper. Paths are relative to the archive's \\lean{src} directory, except in the row "
            "on \\lean{lean4lean}, where they are relative to its repository; a line number "
            "follows a colon; paths beginning \\lean{results/} are in \\lean{verify/} of the "
            "repository of \\cref{app:reproduce}, and those beginning \\lean{refs/} beside the "
            "source of this paper.\n\n"
        )
        f.write("{\\footnotesize\\setlength{\\tabcolsep}{4pt}\n")
        f.write("\\begin{longtable}{@{}>{\\raggedright\\arraybackslash}p{0.36\\textwidth}"
                ">{\\raggedright\\arraybackslash}p{0.12\\textwidth}"
                ">{\\raggedright\\arraybackslash}p{0.46\\textwidth}@{}}\n")
        f.write("\\toprule\nClaim & Level & What was read\\\\\n\\midrule\n\\endhead\n\\bottomrule\n\\endfoot\n")
        for step, claim, lev, read in rows:
            f.write(f"{cell(claim)} & {level(lev)} & {cell(read)}\\\\\n\\addlinespace[2pt]\n")
        f.write("\\end{longtable}}\n")
    print(f"{len(rows)} rows")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
